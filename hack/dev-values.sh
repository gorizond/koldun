#!/usr/bin/env bash
set -euo pipefail

# Generate a temporary Helm values file with random MinIO and CSI S3
# credentials for local development. Nothing is committed to git.
#
# Usage (release name must be "koldun" because the CSI S3 endpoint below is
# derived from it):
#   helm install koldun charts/koldun -n koldun \
#     -f values-dev.yaml -f "$(hack/dev-values.sh)" --wait
#
# The path can be pinned with KOLDUN_DEV_VALUES_FILE.

OUT_FILE="${KOLDUN_DEV_VALUES_FILE:-${TMPDIR:-/tmp}/koldun-dev-secrets.yaml}"

if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required to generate credentials" >&2
    exit 1
fi

ACCESS_KEY="koldun-dev-$(openssl rand -hex 8)"
SECRET_KEY="$(openssl rand -hex 24)"

umask 077
cat >"$OUT_FILE" <<EOF
# Generated by hack/dev-values.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Local development only: do not commit, do not reuse outside a dev machine.
minio:
  enabled: true
  rootUser: "${ACCESS_KEY}"
  rootPassword: "${SECRET_KEY}"
csi-s3:
  enabled: true
  secret:
    accessKey: "${ACCESS_KEY}"
    secretKey: "${SECRET_KEY}"
    endpoint: "http://koldun-minio:9000"
EOF

echo "$OUT_FILE"
